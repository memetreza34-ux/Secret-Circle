'use strict';
const assert = require('node:assert/strict');
const M = require('../party-classic-model.js');
const C = require('../party-wave-one-clue-catalog.js');
const loader = require('../quick-loader.js');
const guard = require('../quick-session-replacement-guard.js');
const release = require('../party-release-structure.js');
const controls = require('../party-session-controls.js');
const people = ['Alex', 'Sam', 'Mika', 'Lina'];
assert.equal(C.games.length, 58);
assert.deepEqual(C.classicGameIds, M.ids);
for (const id of M.ids) {
  const game = C.getGame(id), items = C.getItems(id, C.getPackNames(id)[0]);
  assert.equal(game.status, 'playable'); assert.equal(game.mode, 'link');
  assert.equal(game.href, `quick-play.html?game=${id}`);
  assert.equal(release.tierFor(game), 'labs');
  assert.ok(C.getPackNames(id).length >= 4);
  assert.ok(C.getPackNames(id).every(pack => C.getItems(id, pack).length >= 8));
  assert.equal(controls.familyForGame(C, id), 'mega');
  assert.equal(loader.selectSource(C, id), 'party-classic-modes.js');
  const plan = loader.scriptPlan(C, id);
  assert.ok(plan.indexOf('party-classic-model.js') < plan.indexOf('quick-session-replacement-guard.js'));
  assert.ok(plan.indexOf('party-classic-drawing.js') < plan.indexOf('party-classic-modes.js'));
  const state = M.create(id, items, 3);
  assert.ok(M.valid(id, state, people, items));
  const saved = { version: 1, gameId: id, targetRounds: 3, round: 1, players: people, pack: C.getPackNames(id)[0], phase: 'card', current: state };
  assert.equal(guard.sameGameResumeValid(C, id, saved), true);
  assert.equal(guard.sameGameResumeValid(C, id, { ...saved, current: { ...state, kind: 'falsch' } }), false);
}
const drawingItems = C.getItems('drawing-telephone', 'Alltag');
const chain = M.create('drawing-telephone', drawingItems);
const stroke = [[[5, 6], [20, 30], [900, 850]]];
M.submitDrawing(chain, stroke);
assert.equal(chain.steps.length, 1);
stroke[0][0][0] = 999;
assert.equal(chain.steps[0].strokes[0][0][0], 5, 'Zeichnungen werden kopiert');
M.submitGuess(chain, '<img onerror=alert(1)>');
assert.equal(chain.steps[1].text, '<img onerror=alert(1)>', 'Nutzertext bleibt Text und wird nicht als HTML gerendert');
M.submitDrawing(chain, [], 'Ein Bild mit einer langen Nase');
M.submitGuess(chain, 'Elefant');
chain.stage = 'review';
assert.ok(M.valid('drawing-telephone', chain, people, drawingItems));
assert.equal(M.validDrawing([Array.from({ length: 601 }, () => [1, 2])]), false);
assert.equal(M.validDrawing([[[1001, 2]]]), false);
assert.throws(() => M.submitGuess(chain, 'zu spät'));
assert.equal(M.valid('drawing-telephone', { ...chain, stage: 'play' }, people, drawingItems), false);
const luggage = M.create('packing-suitcase', ['Urlaub']);
M.propose(luggage, 'Sonnenbrille'); assert.equal(M.judge(luggage, true), 1);
assert.deepEqual(luggage.list, ['Sonnenbrille']); assert.equal(luggage.correct, true);
assert.throws(() => M.judge(luggage, true), 'Doppelte Bestätigung darf keinen Punkt ergeben');
luggage.stage = 'recall'; luggage.pending = ''; luggage.correct = null;
assert.throws(() => M.propose(luggage, ' SONNENBRILLE '));
M.propose(luggage, 'Hut'); assert.equal(M.judge(luggage, false), 0);
assert.deepEqual(luggage.list, ['Sonnenbrille']); assert.equal(luggage.correct, false);
assert.ok(M.valid('packing-suitcase', luggage, people));
const terms = C.getItems('three-rounds', 'Tiere');
const state = M.create('three-rounds', terms, 5);
const original = [...state.deck];
for (let phase = 1; phase <= 3; phase++) {
  assert.deepEqual(state.deck, original, 'Alle drei Phasen verwenden denselben Stapel');
  const first = state.bag[0]; M.skip(state);
  assert.equal(state.bag[state.bag.length - 1], first, 'Übersprungene Wörter bleiben erhalten');
  M.endTurn(state); assert.ok(M.valid('three-rounds', state, people, terms));
  const scoreBefore = state.teamScores.reduce((a, b) => a + b, 0);
  for (let i = 0; i < 5; i++) { M.hit(state); assert.ok(M.valid('three-rounds', state, people, terms)); }
  assert.equal(state.teamScores.reduce((a, b) => a + b, 0), scoreBefore + 5);
  assert.throws(() => M.hit(state), 'Doppeltipp nach Phasenende gibt keinen Punkt');
  if (phase < 3) M.nextPhase(state);
}
assert.equal(state.stage, 'done');
assert.equal(state.teamScores.reduce((a, b) => a + b, 0), 15);
assert.equal(M.valid('three-rounds', { ...state, teamScores: [99, 0] }, people, terms), false);
assert.equal(M.valid('three-rounds', { ...state, deck: ['falsch', ...state.deck.slice(1)] }, people, terms), false);
assert.equal(M.valid('three-rounds', { ...state, bag: [0, 0] }, people, terms), false);
console.log(JSON.stringify({ ok: true, newGames: M.ids, totalGames: C.games.length, sharedBackupFamily: 'mega', threeRoundHits: 15, boundedDrawings: true }));
